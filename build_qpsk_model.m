function build_qpsk_model(cfg)
%BUILD_QPSK_MODEL Create the runnable R2022b QPSK ASCII Simulink model.

modelName = 'qpsk_ascii_system';
modelDir = fileparts(cfg.modelFile);
ensure_directory(modelDir);
configure_simulink_file_generation();

if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
new_system(modelName);
cleanup = onCleanup(@() close_if_loaded(modelName)); %#ok<NASGU>

set_param(modelName, ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', 'auto', ...
    'StopTime', '0', ...
    'SaveOutput', 'off', ...
    'SignalLogging', 'off', ...
    'ReturnWorkspaceOutputs', 'on', ...
    'SavedCharacterEncoding', 'UTF-8');

load_system('simulink');
load_system('commdigbbndpm3');
load_system('commfilt2');
load_system('commchan3');

qpskModSource = sprintf( ...
    'commdigbbndpm3/QPSK\nModulator\nBaseband');
qpskDemodSource = sprintf( ...
    'commdigbbndpm3/QPSK\nDemodulator\nBaseband');
rrcTxSource = sprintf('commfilt2/Raised Cosine\nTransmit Filter');
rrcRxSource = sprintf('commfilt2/Raised Cosine\nReceive Filter');
awgnSource = sprintf('commchan3/AWGN\nChannel');
assert_source_blocks({qpskModSource, qpskDemodSource, ...
    rrcTxSource, rrcRxSource, awgnSource});

add_block('simulink/Sources/Constant', ...
    [modelName '/ASCII_Bits_Input'], ...
    'Value', 'txBitsIn', ...
    'SampleTime', 'inf', ...
    'Position', [30 90 120 130]);
add_block(qpskModSource, [modelName '/QPSK_Modulator'], ...
    'InType', 'Bit', 'Enc', 'Gray', 'Ph', 'pi/4', ...
    'Position', [170 75 285 145]);
add_block(rrcTxSource, [modelName '/RRC_Tx_Filter'], ...
    'filtType', 'Square root', ...
    'R', 'simulinkRolloff', ...
    'filtSpan', 'simulinkFilterSpan', ...
    'N', 'simulinkSps', ...
    'InputProcessing', 'Columns as channels (frame based)', ...
    'RateOptions', 'Enforce single-rate processing', ...
    'Position', [335 75 460 145]);
add_block(awgnSource, [modelName '/AWGN_Channel'], ...
    'noiseMode', 'Signal to noise ratio  (SNR)', ...
    'SNRdB', 'simulinkSNRdB', ...
    'InputProcessing', 'Columns as channels (frame based)', ...
    'seed', 'simulinkNoiseSeed', ...
    'Position', [510 75 620 145]);
add_block(rrcRxSource, [modelName '/RRC_Rx_Filter'], ...
    'filtType', 'Square root', ...
    'R', 'simulinkRolloff', ...
    'filtSpan', 'simulinkFilterSpan', ...
    'N', 'simulinkSps', ...
    'downFactor', '1', ...
    'InputProcessing', 'Columns as channels (frame based)', ...
    'RateOptions', 'Enforce single-rate processing', ...
    'Position', [670 75 795 145]);
add_block('simulink/Signal Routing/Selector', ...
    [modelName '/Symbol_Sampling'], ...
    'NumberOfDimensions', '1', ...
    'IndexMode', 'One-based', ...
    'IndexOptions', 'Index vector (dialog)', ...
    'Indices', 'simulinkSampleIndices', ...
    'InputPortWidth', 'simulinkWaveformLength', ...
    'OutputSizes', 'numel(simulinkSampleIndices)', ...
    'Position', [845 85 935 135]);
add_block(qpskDemodSource, [modelName '/QPSK_Demodulator'], ...
    'OutType', 'Bit', 'Dec', 'Gray', 'Ph', 'pi/4', ...
    'DecType', 'Hard decision', ...
    'Position', [985 75 1110 145]);
add_block('simulink/Sinks/To Workspace', ...
    [modelName '/Recovered_Bits'], ...
    'VariableName', 'rxBitsLog', ...
    'SaveFormat', 'Array', ...
    'Position', [1160 75 1270 115]);
add_block('simulink/Sinks/Terminator', ...
    [modelName '/ASCII_Output_Verification'], ...
    'Position', [1325 120 1345 140]);

connect_chain(modelName, {'ASCII_Bits_Input', 'QPSK_Modulator', ...
    'RRC_Tx_Filter', 'AWGN_Channel', 'RRC_Rx_Filter', ...
    'Symbol_Sampling', 'QPSK_Demodulator', 'Recovered_Bits'});
add_line(modelName, 'QPSK_Demodulator/1', ...
    'ASCII_Output_Verification/1', 'autorouting', 'on');

add_logger(modelName, 'ASCII_Bits_Input/1', 'Log_Tx_Bits', ...
    'txBitsLog', [40 235 145 275]);
add_logger(modelName, 'QPSK_Modulator/1', 'Log_Tx_Symbols', ...
    'txSymLog', [190 235 305 275]);
add_logger(modelName, 'RRC_Tx_Filter/1', 'Log_Tx_Waveform', ...
    'txWaveLog', [350 235 465 275]);
add_logger(modelName, 'AWGN_Channel/1', 'Log_Rx_Waveform', ...
    'rxWaveLog', [510 235 625 275]);
add_logger(modelName, 'RRC_Rx_Filter/1', 'Log_Matched_Waveform', ...
    'matchedLog', [675 235 805 275]);
add_logger(modelName, 'Symbol_Sampling/1', 'Log_Rx_Symbols', ...
    'rxSymLog', [845 235 950 275]);

set_param([modelName '/ASCII_Bits_Input'], ...
    'AttributesFormatString', 'ASCII text converted to 8-bit MSB-first data');
set_param([modelName '/ASCII_Output_Verification'], ...
    'AttributesFormatString', ...
    'Recovered ASCII decoded and checked by run_simulink_demo.m');
set_param(modelName, 'Description', sprintf([ ...
    'QPSK ASCII communication chain for MATLAB R2022b.\n' ...
    'ASCII conversion and final text verification are performed by ' ...
    'run_simulink_demo.m; all physical-link stages run in this model.']));

assign_model_variables(modelName, cfg);
set_param(modelName, 'SimulationCommand', 'update');
save_system(modelName, cfg.modelFile);
end

function connect_chain(modelName, blocks)
for k = 1:numel(blocks)-1
    add_line(modelName, [blocks{k} '/1'], [blocks{k+1} '/1'], ...
        'autorouting', 'on');
end
end

function add_logger(modelName, sourcePort, blockName, variableName, position)
add_block('simulink/Sinks/To Workspace', [modelName '/' blockName], ...
    'VariableName', variableName, 'SaveFormat', 'Array', ...
    'Position', position);
add_line(modelName, sourcePort, [blockName '/1'], 'autorouting', 'on');
end

function assign_model_variables(modelName, cfg)
bits = double(ascii_to_bits(cfg.message));
tailBits = zeros(2*cfg.filterSpanSymbols, 1);
symbolCount = numel(bits)/cfg.bitsPerSymbol;
modelWorkspace = get_param(modelName, 'ModelWorkspace');
assignin(modelWorkspace, 'txBitsIn', [bits; tailBits]);
assignin(modelWorkspace, 'simulinkRolloff', cfg.rolloff);
assignin(modelWorkspace, 'simulinkFilterSpan', cfg.filterSpanSymbols);
assignin(modelWorkspace, 'simulinkSps', cfg.sps);
assignin(modelWorkspace, 'simulinkNoiseSeed', cfg.functionalSeed);
assignin(modelWorkspace, 'simulinkSNRdB', cfg.functionalEbNoDb + ...
    10*log10(cfg.bitsPerSymbol) - 10*log10(cfg.sps));
assignin(modelWorkspace, 'simulinkWaveformLength', ...
    (symbolCount + cfg.filterSpanSymbols)*cfg.sps);
firstSample = cfg.filterSpanSymbols*cfg.sps + 1;
assignin(modelWorkspace, 'simulinkSampleIndices', ...
    firstSample:cfg.sps:firstSample+(symbolCount-1)*cfg.sps);
end

function assert_source_blocks(blocks)
for k = 1:numel(blocks)
    if getSimulinkBlockHandle(blocks{k}) < 0
        error('qpsk:MissingSimulinkBlock', ...
            'Required R2022b block is unavailable: %s', ...
            strrep(blocks{k}, newline, ' / '));
    end
end
end

function ensure_directory(pathToCreate)
if ~isfolder(pathToCreate)
    [created, message] = mkdir(pathToCreate);
    if ~created
        error('qpsk:OutputDirectoryCreationFailed', '%s', message);
    end
end
end

function close_if_loaded(modelName)
if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
end
